    private static final java.util.logging.Logger logger = java.util.logging.Logger.getLogger(GameFrame.class.getName());

    private final CardLayout cardLayout;
    private final GameManager gameManager = new GameManager();

    private final MainMenuPanel mainMenuPanel;
    private final SettingsPanel settingsPanel;
    private final TutorialPanel tutorialPanel;
    private final GameplayPanel gameplayPanel;
    private Screen currentScreen;
    
    public GameFrame() {
        initComponents();
        
        cardLayout = (CardLayout) cards.getLayout();
        mainMenuPanel = new MainMenuPanel(this);
        settingsPanel = new SettingsPanel(this);
        tutorialPanel = new TutorialPanel(this);
        gameplayPanel = new GameplayPanel(this, gameManager);

        cards.add(mainMenuPanel, "MENU");
        cards.add(settingsPanel, "SETTINGS");
        cards.add(tutorialPanel, "TUTORIAL");
        cards.add(gameplayPanel, "GAME");
        showMenu();
    }
    
    /** Switches card and tells the old/new screen (polymorphic Screen hooks). */
    private void show(String card, Screen screen) {
        if (currentScreen != null) {
            currentScreen.onHide();
        }
        cardLayout.show(cards, card);
        currentScreen = screen;
        screen.onShow();
    }

    @Override
    public void showMenu() {
        show("MENU", mainMenuPanel);
    }

    @Override
    public void showSettings() {
        show("SETTINGS", settingsPanel);
    }

    @Override
    public void showTutorial() {
        show("TUTORIAL", tutorialPanel);
    }

    @Override
    public void startNewGame() {
        gameManager.restartGame();
        show("GAME", gameplayPanel);
    }

