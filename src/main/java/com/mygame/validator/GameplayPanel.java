    /** Screen hook: the game screen appeared, so start the first briefing and the game music. */
    @Override
    public void onShow() {
        stopBriefingTimer();
        audio.playMusic("game");
        showBriefing();
    }

    /** Screen hook: leaving the game screen must stop the countdown. */
    @Override
    public void onHide() {
        stopBriefingTimer();
    }

    /** Phase 1: main news enlarged; articles not yet shown. */
    private void showBriefing() {
        if (manager.isGameOver()) {
            showResults();
            return;
        }
        phase = Phase.BRIEFING;
        updateStatus();

        Level level = manager.getCurrentLevel();
        mainCard.setContent(level.getMainNews());                 // overload: from a news item
        mainCard.setTagText(level.getMainNews().getKindLabel());
        mainCard.setAccent(BLUE);
        setMainCardExpanded(true);
        mainCard.setToggleEnabled(false);

        articlesPanel.setVisible(false);
        feedbackArea.setText("Read the briefing. The two articles appear after the timer ends, or when you click Continue.");
        continueButton.setText("Continue to Articles");
        continueButton.setEnabled(true);

        feedbackArea.setForeground(Color.WHITE);
        briefingStartNs = System.nanoTime();
        updateTimerHud();
        briefingTimer = new Timer(100, e -> {
            updateTimerHud();
            if (briefingSecondsLeft() <= 0) {
                showArticles();
            }
        });
        briefingTimer.start();
        audio.play("news_enter");
    }

    /** Phase 2: main news minimized in the middle, two articles minimized at the bottom. */
    private void showArticles() {
        stopBriefingTimer();
        phase = Phase.DECIDING;
        updateStatus();

        mainCard.setTagText("MAIN NEWS");
        if (mainCard.isExpanded()) {
            audio.play("news_exit");
        }
        setMainCardExpanded(false);
        mainCard.setToggleEnabled(true);
        audio.play("choice_enter");
        updateTimerHud();

        List<Article> articles = manager.getDisplayedArticles();
        for (int i = 0; i < 2; i++) {
            articleCards[i].setContent(articles.get(i));
            articleCards[i].setTagText("ARTICLE " + (char) ('A' + i));
            articleCards[i].setAccent(GRAY);
            articleCards[i].setExpanded(false);
            articleCards[i].setToggleEnabled(true);
            articleCards[i].setRemoveEnabled(true);
        }
        articlesPanel.setVisible(true);

        feedbackArea.setText("Click Enlarge on the main news or either article to read it. "
                + "Then REMOVE the article that is fake or unsupported - the other one stays "
                + "as your retained news.");
        continueButton.setText("Next Level");
        continueButton.setEnabled(false);
        revalidate();
        repaint();
    }

    /** Phase 3: the player removed an article; evaluate the retained one. */
    private void onRemoveClicked(int removedIndex) {
        if (phase != Phase.DECIDING) {
            return;
        }
        int retainedIndex = 1 - removedIndex;
        String removedName = "Article " + (char) ('A' + removedIndex);
        String retainedName = "Article " + (char) ('A' + retainedIndex);

        audio.play("choice_grab");
        if (!confirmRemoval(removedName, retainedName)) {
            audio.play("choice_ungrab");
            return;
        }
        audio.play("choice_destroy");

        List<Article> articles = manager.getDisplayedArticles();
        Article removed = articles.get(removedIndex);
        Article retained = articles.get(retainedIndex);
        boolean correct = manager.removeArticle(removed);      // overload: by article
        phase = Phase.RESULT;
        updateStatus();

        for (CollapsibleCard card : articleCards) {
            card.setRemoveEnabled(false);
        }

        articleCards[removedIndex].setTagText(removedName + " - REMOVED");
        articleCards[removedIndex].setAccent(GRAY);
        articleCards[retainedIndex].setTagText(retainedName + " - RETAINED");
        articleCards[retainedIndex].setAccent(correct ? GREEN : RED);
        articleCards[retainedIndex].setBody(retained.getBody()
                + "\n\nFACT-CHECK: " + retained.getExplanation());
        articleCards[removedIndex].setBody(removed.getBody()
                + "\n\nFACT-CHECK: " + removed.getExplanation());

        String delta = correct ? "+" + GameManager.CREDIBILITY_CHANGE : "-" + GameManager.CREDIBILITY_CHANGE;
        String verdict = correct
                ? "CORRECT! The retained news (" + retainedName + ") is credible."
                : "INCORRECT. The retained news (" + retainedName + ") is fake or unsupported.";
        feedbackArea.setText(verdict + " Credibility " + delta + " points.\n"
                + retainedName + " (retained): " + retained.getExplanation() + "\n"
                + removedName + " (removed): " + removed.getExplanation());
        feedbackArea.setCaretPosition(0);
        feedbackArea.setForeground(correct ? LIGHT_GREEN : LIGHT_RED);
        audio.play(correct ? "reputation_good" : "reputation_bad");
        audio.play(correct ? "emoji_1" : "emoji_2");

        continueButton.setText(manager.isLastLevel() ? "View Final Results" : "Next Level");
        continueButton.setEnabled(true);
    }

    /** Asks the player to confirm the removal (a misclick would cost credibility). */
    protected boolean confirmRemoval(String removedName, String retainedName) {
        int confirm = JOptionPane.showConfirmDialog(this,
                "Remove " + removedName + " and retain " + retainedName + "?",
                "Confirm removal", JOptionPane.YES_NO_OPTION);
        return confirm == JOptionPane.YES_OPTION;
    }

    private void handleContinue() {
        if (phase == Phase.BRIEFING) {
            showArticles();
        } else if (phase == Phase.RESULT) {
            feedbackArea.setForeground(Color.WHITE);
            manager.nextLevel();
            if (manager.isGameOver()) {
                audio.play("next_level_outro");
                showResults();
            } else {
                audio.play("next_level");
                showBriefing();
            }
        }
    }
    
