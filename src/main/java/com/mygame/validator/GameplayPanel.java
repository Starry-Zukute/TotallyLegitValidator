    /** Main news: fills the middle when enlarged; sits minimized in the middle when not. */
    private void layoutMainCard() {
        GridBagConstraints gc = new GridBagConstraints();
        gc.gridx = 0;
        gc.gridy = 0;
        gc.weightx = 1;
        gc.anchor = GridBagConstraints.CENTER;
        if (mainCard.isExpanded()) {
            gc.fill = GridBagConstraints.BOTH;
            gc.weighty = 1;
        } else {
            gc.fill = GridBagConstraints.HORIZONTAL;
            gc.weighty = 0;
        }
        ((GridBagLayout) centerHolder.getLayout()).setConstraints(mainCard, gc);
        centerHolder.revalidate();
        centerHolder.repaint();
    }

    private double briefingSecondsLeft() {
        double elapsed = (System.nanoTime() - briefingStartNs) / 1e9;
        return Math.max(0, BRIEFING_SECONDS - elapsed);
    }

    /** Clock + seconds + bar during the briefing; "--" and an empty bar afterwards. */
    private void updateTimerHud() {
        if (phase == Phase.BRIEFING) {
            double left = briefingSecondsLeft();
            timerLabel.setText("Time: " + (int) Math.ceil(left) + "s");
            timerBar.setValue((int) Math.round(left * 10));
        } else {
            timerLabel.setText("Time: --");
            timerBar.setValue(0);
        }
    }

    private void updateStatus() {
        int levelNumber = Math.min(manager.getLevelNumber(), GameManager.TOTAL_LEVELS);
        levelLabel.setText("Level " + levelNumber + " / " + GameManager.TOTAL_LEVELS);
        credibilityLabel.setText("Credibility: " + manager.getCredibility() + "%");
        credibilityBar.setValue(manager.getCredibility());
        credibilityBar.setString(manager.getCredibility() + "%");
    }

    private void stopBriefingTimer() {
        if (briefingTimer != null) {
            briefingTimer.stop();
            briefingTimer = null;
        }
    }

    private void showResults() {
        stopBriefingTimer();
        continueButton.setEnabled(false);

        String message = "All " + GameManager.TOTAL_LEVELS + " levels completed!\n\n"
                + "Final credibility: " + manager.getCredibility() + "%\n"
                + "Correct levels: " + manager.getCorrectDecisions() + "\n"
                + "Incorrect levels: " + manager.getIncorrectDecisions() + "\n\n"
                + "Would you like to try again? A new game will shuffle all levels.";
        Object[] options = {"Try Again (New Shuffle)", "Main Menu"};
        int choice = JOptionPane.showOptionDialog(
                this, message, "Game Complete",
                JOptionPane.DEFAULT_OPTION, JOptionPane.INFORMATION_MESSAGE,
                null, options, options[0]);

        if (choice == 0) {
            navigator.startNewGame();
        } else {
            navigator.showMenu();
        }
    }
    
    private void playToggleSound(CardEvent evt) {
    audio.play(evt.isExpanded() ? "description_sound" : "choice_exit");
    }

/** Programmatic resize of the main news (the toggled event only fires for the player's clicks). */
    private void setMainCardExpanded(boolean expanded) {
    mainCard.setExpanded(expanded);
    layoutMainCard();
    }
    
    

